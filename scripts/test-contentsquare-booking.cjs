const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync(require('node:path').join(__dirname, '../primal.js'), 'utf8');
const bridge = source.slice(source.indexOf('  function contentsquareBookingEvent('), source.indexOf('  function emit('));
const start = source.indexOf("    window.addEventListener('message', function (e)");
const listener = source.slice(start, source.indexOf('\n    });', start) + '\n    });'.length);
const frameWindow = {};
const emitted = [], beacons = [];
const window = {primalMarketingAllowed: false, addEventListener: (_, fn) => window.listener = fn};
const context = vm.createContext({window, page:'recovery', scheduleFired:false, calNode:{querySelector:()=>({contentWindow:frameWindow})}, emit:(name)=>{emitted.push(name);context.contentsquareBookingEvent(name);}, funnelBeacon:name=>beacons.push(name)});
vm.runInContext(bridge + listener, context);
context.contentsquareBookingEvent('calendar_visible');
assert.equal(window._uxa, undefined, 'no queue without consent');
window.primalMarketingAllowed = true;
context.contentsquareBookingEvent('calendar_visible');
assert.equal(window._uxa[0][1], 'recovery_calendar_visible');
context.contentsquareBookingEvent('email@example.com');
assert.equal(window._uxa.length, 1, 'only allowlisted names');
context.page = 'pricing';context.contentsquareBookingEvent('calendar_loaded');
assert.equal(window._uxa.length, 1, 'recovery only');context.page = 'recovery';
const send = (event, origin='https://calendly.com', source=frameWindow) => window.listener({origin,source,data:{event,payload:{email:'private@example.com'}}});
send('calendly.event_scheduled','https://evil.example');
send('calendly.event_scheduled','https://calendly.com',{});
assert.equal(emitted.length, 0, 'reject wrong origin and frame');
send('calendly.event_type_viewed');send('calendly.date_and_time_selected');send('calendly.event_scheduled');send('calendly.event_scheduled');
assert.deepEqual(emitted,['booking_screen_displayed','booking_time_selected','booking_completed']);
assert.deepEqual(beacons,['booking_time_selected'], 'no browser booking conversion beacon');
assert.ok(!JSON.stringify(window._uxa).includes('private@example.com'));
window.primalMarketingAllowed = false;
const count=window._uxa.length;context.contentsquareBookingEvent('calendar_visible');
assert.equal(window._uxa.length,count,'respects consent withdrawal');
console.log('PASS: consent, allowlist, route, event forwarding, source validation, deduplication, and no booking PII');
